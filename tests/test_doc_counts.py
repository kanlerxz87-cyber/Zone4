"""Tests for the generated-count gate (SG-37 mechanism; added 2026-11-19).

The gate has two halves: the parsing/fixing primitives must handle every
document shape exactly (numbers change, prose never does), and the real
repository must currently pass, so a hand-edited numeral cannot ship.
"""
import importlib.util
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
_SPEC = importlib.util.spec_from_file_location(
    "check_doc_counts", ROOT / "scripts" / "check_doc_counts.py"
)
cdc = importlib.util.module_from_spec(_SPEC)
_SPEC.loader.exec_module(cdc)


class SentenceParsing(unittest.TestCase):
    def test_flexible_sentence_matches_both_document_shapes(self):
        # README shape ("..., **52 decisions** (39 recorded, 13 open), and **90 flags**")
        readme = (
            "The suggestion and decision pages are the review gate: "
            "**7 suggestions**, **5 questions**, **4 decisions** (3 recorded, 1 open), "
            "and **9 flags** are maintained in the JSON registers."
        )
        # EXECUTIVE_SUMMARY shape ("..., and **52 decisions** (39 recorded; 13 open), with **90 flags**")
        exec_summary = (
            "The decision-support system contains **7 suggestions**, **5 questions**, "
            "and **4 decisions** (3 recorded; 1 open), with **9 flags**."
        )
        for text in (readme, exec_summary):
            self.assertEqual(
                cdc.extract(text, cdc.COUNT_SURFACES[0]["pattern"]),
                [7, 5, 4, 3, 1, 9],
                msg=text,
            )

    def test_drift_is_detected_per_number(self):
        counts = {"suggestions": 8, "questions": 5, "decisions": 4,
                  "recorded": 3, "open": 1, "flags": 9}
        text = "review gate: **7 suggestions**, **5 questions**, **4 decisions** (3 recorded, 1 open), and **9 flags**"
        drifts = []
        m = cdc.re.search(cdc.COUNT_SURFACES[0]["pattern"], text)
        for i, key in enumerate(cdc.COUNT_SURFACES[0]["keys"], start=1):
            if int(m.group(i)) != counts[key]:
                drifts.append(key)
        self.assertEqual(drifts, ["suggestions"])

    def test_missing_sentence_returns_no_numbers(self):
        # An absent sentence must read as "no numbers found", so the gate can
        # report a missing anchor loudly instead of silently skipping it.
        text = "the counts live elsewhere now"
        self.assertEqual(cdc.extract(text, cdc.COUNT_SURFACES[0]["pattern"]), [])


class FixRewrites(unittest.TestCase):
    def test_fix_corrects_numerals_without_touching_prose(self):
        counts = {"suggestions": 8, "questions": 5, "decisions": 4,
                  "recorded": 3, "open": 1, "flags": 9}
        text = (
            "The suggestion and decision pages are the review gate: "
            "**7 suggestions**, **5 questions**, **4 decisions** (3 recorded, 1 open), "
            "and **9 flags** are maintained in the JSON registers."
        )
        fixed = cdc.fix_text(text, cdc.COUNT_SURFACES[0]["pattern"],
                             cdc.COUNT_SURFACES[0]["keys"], counts)
        self.assertIn("**8 suggestions**", fixed)
        self.assertIn("and **9 flags** are maintained", fixed)
        # Prose is byte-identical outside the numerals.
        self.assertEqual(
            cdc.re.sub(r"\d+", "N", text), cdc.re.sub(r"\d+", "N", fixed)
        )

    def test_engine_comment_is_regenerated_with_a_do_not_edit_note(self):
        line = "python3 -m unittest discover -s tests     # 92 tests (83 engine + 9 analytics endpoint), stdlib only"
        surface = cdc.COUNT_SURFACES[-1]
        self.assertTrue(surface["line_anchor"] in line)
        self.assertIsNotNone(cdc.re.search(surface["pattern"], line))
        # fix() rewrites the whole comment; simulate its line logic here.
        counts = {"tests": 97}
        head, sep, _tail = line.partition("#")
        rebuilt = head.rstrip() + "  # " + f"{counts['tests']} tests, " + cdc.ENGINE_COMMENT_NOTE
        self.assertEqual(
            rebuilt,
            "python3 -m unittest discover -s tests  # 97 tests, stdlib only "
            "(count generated by scripts/check_doc_counts.py --fix; do not hand-edit)",
        )
        self.assertIn("do not hand-edit", rebuilt)


class RepoGate(unittest.TestCase):
    def test_no_hand_typed_count_disagrees_with_the_registers(self):
        # The real tree must pass: any hand-edited numeral in README.md,
        # EXECUTIVE_SUMMARY.md, data/content.json or ENGINE.md fails here.
        self.assertEqual(cdc.check(), [])

    def test_register_counts_shape(self):
        counts = cdc.register_counts()
        for key in ("suggestions", "questions", "decisions", "recorded",
                    "open", "flags", "requirements", "tests"):
            self.assertIn(key, counts)
        self.assertGreater(counts["tests"], 0)
        self.assertEqual(counts["recorded"] + counts["open"], counts["decisions"])


if __name__ == "__main__":
    unittest.main()
